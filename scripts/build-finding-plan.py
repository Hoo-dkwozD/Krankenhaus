#!/usr/bin/env python3
"""Compile the active finding plan from engagement metadata and the Markdown catalogue."""
from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "engagement.yaml"
ROLES = ROOT / "config" / "roles.csv"
CATALOGUE = ROOT / "catalogue" / "Finding-Catalogue.md"
OUTPUT = ROOT / "plans" / "Finding-Plan.md"


def simple_yaml(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, value = line.split(":", 1)
        values[key.strip()] = value.strip().strip('"\'')
    return values


def read_roles() -> list[dict[str, str]]:
    with ROLES.open(newline="", encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    return [row for row in rows if row.get("enabled", "true").lower() == "true"]


def read_catalogue() -> list[dict[str, str]]:
    category = "Uncategorized"
    current: dict[str, str] | None = None
    entries: list[dict[str, str]] = []
    for raw in CATALOGUE.read_text(encoding="utf-8").splitlines():
        if raw.startswith("## "):
            category = raw[3:].strip()
            continue
        match = re.match(r"^### (CXC-[A-Z0-9-]+) — (.+)$", raw)
        if match:
            current = {
                "id": match.group(1),
                "title": match.group(2).strip(),
                "category": category,
                "priority": "P2",
                "surface": "EDIT_ME",
            }
            entries.append(current)
            continue
        if current is None:
            continue
        priority = re.match(r"^- Default priority: (P[0-3])$", raw.strip())
        surface = re.match(r"^- Surface: (.+)$", raw.strip())
        if priority:
            current["priority"] = priority.group(1)
        if surface:
            current["surface"] = surface.group(1).strip()
    return entries


def main() -> None:
    config = simple_yaml(CONFIG)
    roles = read_roles()
    entries = read_catalogue()
    grouped: dict[str, list[dict[str, str]]] = {}
    for entry in entries:
        grouped.setdefault(entry["category"], []).append(entry)

    lines = [
        "# Finding Plan",
        "",
        "> Generated by `scripts/build-finding-plan.py`. Edit the catalogue and engagement metadata, then regenerate.",
        "",
        "## Engagement context",
        "",
        f"- Project: `{config.get('project_name', 'EDIT_ME')}`",
        f"- Client: `{config.get('client', 'EDIT_ME')}`",
        f"- Target: `{config.get('primary_url', 'EDIT_ME')}`",
        f"- Burp MCP: `{config.get('burp_mcp_endpoint', 'EDIT_ME')}`",
        "- Role order: **Super Admin → Admin → Supervisor → Agent**",
        "- Default status: `Planned`",
        "",
        "## Active roles",
        "",
        "| Order | Role | Username | Tenant | Enabled |",
        "|---:|---|---|---|---|",
    ]
    for row in roles:
        lines.append(
            f"| {row.get('order', '')} | {row.get('role', '')} | {row.get('username', '')} | "
            f"{row.get('tenant', '')} | {row.get('enabled', '')} |"
        )
    lines += [
        "",
        "## Execution rules",
        "",
        "1. Reconcile each item against the current Burp sitemap and rendered UI.",
        "2. Map every input/entry point and role before testing an input-heavy family.",
        "3. Test reachable roles in the listed order and batch no more than 20 mapped inputs per run.",
        "4. Require a conclusive precondition/action/postcondition/replay/control/cleanup record before promotion.",
        "5. Mark browser, WebSocket, mutation, cross-tenant, fixture, protocol, and approval gaps explicitly.",
        "",
    ]
    for category, category_entries in grouped.items():
        lines += [f"## {category}", "", "| ID | Title | Default priority | Surface | Status |", "|---|---|---:|---|---|"]
        for entry in category_entries:
            surface = entry["surface"].replace("|", "\\|")
            lines.append(f"| `{entry['id']}` | {entry['title']} | {entry['priority']} | {surface} | Planned |")
        lines.append("")
    lines += [
        "## Dynamic additions",
        "",
        "Add engagement-specific findings below when recon identifies a technology, endpoint, workflow, integration, or data class not covered by the baseline catalogue.",
        "",
        "| ID | Title | Triggering surface | Roles/tenants | Status | Evidence |",
        "|---|---|---|---|---|---|",
        "| CUSTOM-0001 | EDIT_ME | EDIT_ME | EDIT_ME | Planned | |",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {len(entries)} catalogue entries at {OUTPUT}")


if __name__ == "__main__":
    main()
