#!/usr/bin/env python3
"""Generate LLM-mode machine state from human-readable Markdown sources."""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "llm" / "engagement"
GENERATED = ROOT / "llm" / "generated"


def clean(value: str) -> str:
    return value.replace("`", "").strip()


def key_name(value: str) -> str:
    value = value.lower().replace("/", "_")
    value = re.sub(r"[^a-z0-9]+", "_", value)
    return value.strip("_")


def tables(path: Path) -> list[list[dict[str, str]]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    found: list[list[dict[str, str]]] = []
    index = 0
    while index < len(lines) - 1:
        if not (lines[index].strip().startswith("|") and lines[index + 1].strip().startswith("|")):
            index += 1
            continue
        headers = [clean(part) for part in lines[index].strip().strip("|").split("|")]
        separators = [part.strip() for part in lines[index + 1].strip().strip("|").split("|")]
        if not headers or len(headers) != len(separators):
            index += 1
            continue
        if not all(set(part) <= {"-", ":", " "} for part in separators):
            index += 1
            continue
        rows: list[dict[str, str]] = []
        index += 2
        while index < len(lines) and lines[index].strip().startswith("|"):
            values = [clean(part) for part in lines[index].strip().strip("|").split("|")]
            if len(values) == len(headers):
                rows.append({key_name(headers[pos]): values[pos] for pos in range(len(headers))})
            index += 1
        found.append(rows)
    return found


def all_rows(path: Path) -> list[dict[str, str]]:
    result: list[dict[str, str]] = []
    for table in tables(path):
        result.extend(table)
    return result

def selected_rows(path: Path, required_headers: set[str]) -> list[dict[str, str]]:
    for table in tables(path):
        if table and required_headers.issubset(table[0]):
            return table
    return []


def engagement_fields() -> dict[str, str]:
    result: dict[str, str] = {}
    for row in all_rows(SOURCE / "LLM-Engagement-Info.md"):
        if "field" in row and "value" in row:
            result[key_name(row["field"])] = clean(row["value"])
    return result


def yaml_value(value: str) -> str:
    value = clean(value)
    if value.lower() in {"true", "false"}:
        return value.lower()
    return "'" + value.replace("'", "''") + "'"


def write_yaml(fields: dict[str, str]) -> None:
    keys = [
        "mode", "client", "project_name", "engagement_id", "authorized_by", "authorization_reference",
        "environment", "start_utc", "end_utc", "jurisdictions", "languages_supported",
        "languages_to_probe", "use_case_description", "primary_audience", "age_range_minors_possible",
        "vulnerable_populations", "user_roles_personas", "key_workflows", "regulated_or_high_impact_decisions",
        "required_escalation_behavior", "required_disclaimers", "allowed_tone_persona",
        "prohibited_commitments_actions", "client_policy_references", "legal_or_compliance_guidance",
        "reportable_success_threshold", "max_cost_usd", "max_requests_per_minute", "max_turns_per_conversation",
        "max_attempts_per_objective", "reproduction_trials_n", "confirm_threshold", "evidence_store_reference",
        "retention_days", "report_redaction_required", "escalation_contact",
    ]
    lines = ["# GENERATED FILE — edit llm/engagement/*.md, then run scripts/build-llm-state.py."]
    for key in keys:
        lines.append(f"{key}: {yaml_value(fields.get(key, 'EDIT_ME'))}")
    lines += [
        "target_source: llm/engagement/LLM-Target-Context.md",
        "policy_source: llm/engagement/LLM-Policy-Matrix.md",
        "testing_plan_source: llm/engagement/LLM-Testing-Plan.md",
        "playbook_index: llm/playbooks/Playbook-Index.md",
        "playbook_directory: llm/playbooks",
        "context_bank: resource-bank",
        "evidence_directory: llm/evidence",
        "finding_directory: llm/findings",
        "dynamic_objective_discovery: NOT_IMPLEMENTED",
    ]
    (GENERATED / "llm-engagement.yaml").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_csv(filename: str, rows: list[dict[str, str]], headers: list[str]) -> None:
    with (GENERATED / filename).open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=headers)
        writer.writeheader()
        for row in rows:
            writer.writerow({header: row.get(header, "") for header in headers})


def write_plan(objectives: list[dict[str, str]]) -> None:
    lines = [
        "# LLM Finding Plan",
        "",
        "> Generated by `scripts/build-llm-state.py`. Edit `llm/engagement/*.md`, then regenerate.",
        "",
        "## Current mode",
        "",
        "- Mode: LLM testing",
        "- Dynamic objective discovery: not implemented; placeholder list is active",
        "- Active source objective: `LLM-UC-01 — Undesirable Content`",
        "- Human approval: required before any campaign",
        "",
        "## Active objectives",
        "",
        "| Objective ID | Title | Playbook reference | Target IDs | Policy cells | Baseline | Adversarial | Reproduction N | Status |",
        "|---|---|---|---|---|---|---|---:|---|",
    ]
    for row in objectives:
        lines.append(
            f"| `{row.get('objective_id', '')}` | {row.get('title', '')} | {row.get('playbook_reference', '')} | "
            f"{row.get('target_ids', '')} | {row.get('policy_cells', '')} | {row.get('baseline_required', '')} | "
            f"{row.get('adversarial_required', '')} | {row.get('reproduction_n', '')} | {row.get('status', '')} |"
        )
    lines += [
        "",
        "## Activation blockers",
        "",
        "- Exact prompt-insertion endpoint and response extraction path must be completed.",
        "- Business/user context and policy matrix must be approved.",
        "- Target model, provider, parameters, guardrails, memory, tools, and evidence handling must be recorded.",
        "- Budgets, kill switch, hard exclusions, proxy-only objectives, judge setup, and human reviewer must be approved.",
    ]
    (GENERATED / "LLM-Finding-Plan.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    required = [
        SOURCE / "LLM-Engagement-Info.md",
        SOURCE / "LLM-Target-Context.md",
        SOURCE / "LLM-Policy-Matrix.md",
        SOURCE / "LLM-Testing-Plan.md",
    ]
    missing = [str(path) for path in required if not path.is_file()]
    if missing:
        print("Missing LLM source file(s):", *missing, sep="\n- ", file=sys.stderr)
        return 1
    GENERATED.mkdir(parents=True, exist_ok=True)
    fields = engagement_fields()
    write_yaml(fields)
    write_csv(
        "llm-targets.csv",
        selected_rows(SOURCE / "LLM-Target-Context.md", {"target_id", "endpoint", "prompt_insertion_path"}),
        [
            "target_id", "surface_type", "endpoint", "method", "auth_reference", "prompt_insertion_path",
            "response_extraction_path", "streaming", "multi_turn", "upload_rag_surface", "tools_actions",
            "memory_session", "model_name", "model_version", "provider", "system_prompt_visibility",
            "guardrail_layers", "production_parameters", "status", "notes",
        ],
    )
    write_csv(
        "llm-policy-matrix.csv",
        selected_rows(SOURCE / "LLM-Policy-Matrix.md", {"cell_code", "item", "in_scope"}),
        [
            "cell_code", "item", "bucket", "sub_category", "in_scope", "policy_reference", "rule_context",
            "violation_criteria", "not_a_violation", "default_severity", "seed_objective_reference",
            "confirm_threshold", "notes",
        ],
    )
    objectives = selected_rows(SOURCE / "LLM-Testing-Plan.md", {"objective_id", "title"})
    objective_rows = [row for row in objectives if "objective_id" in row]
    write_csv(
        "llm-campaign-matrix.csv",
        objective_rows,
        [
            "objective_id", "title", "playbook_reference", "target_ids", "policy_cells", "baseline_required",
            "adversarial_required", "reproduction_n", "status", "notes",
        ],
    )
    write_plan(objective_rows)
    print(f"Generated LLM state with {len(objective_rows)} objective(s): {GENERATED}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
